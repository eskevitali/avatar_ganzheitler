// Run against an already running local preview. Uses a temporary, clearly labelled test package.
import {createRequire} from 'node:module';
import {readFile, mkdir, writeFile, rm} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {install} from '../scripts/install-profile.mjs';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:3100';
const source = new URL('../.local-preview/browser-fixture/', import.meta.url);
const installed = new URL('../public/profiles/browser-fixture/', import.meta.url);
await mkdir(source, {recursive: true});
await writeFile(new URL('profile.json', source), JSON.stringify({formatVersion: 1, id: 'browser-fixture', name: 'TEST ONLY — training model fixture', model: 'model.glb', body: 'F', defaults: {mood: 'sad', lips: {PP: {jawOpen: 0.67}}}}));
await writeFile(new URL('model.glb', source), await readFile(new URL('../public/dolls/brunette.glb', import.meta.url)));
await rm(installed, {recursive: true, force: true});
await install(source.pathname);
const browser = await chromium.launch({headless: true, executablePath: process.env.CHROME_PATH || '/opt/google/chrome/chrome', args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
try {
  const page = await browser.newPage({viewport: {width: 1100, height: 1000}});
  const errors = [];
  page.on('pageerror', e => {errors.push(e.message); console.error('PAGE ERROR:', e.message);});
  page.on('console', e => {if(e.type() === 'error' && !e.text().startsWith('Failed to load resource:')) errors.push(e.text());});
  const response = await page.request.get(`${base}/api/profiles`);
  assert.equal(response.status(), 401);
  await page.goto(base);
  await page.locator('#password').fill((await readFile(new URL('../.local-preview/access.txt', import.meta.url), 'utf8')).trim());
  await page.locator('#login-form button').click();
  await page.locator('#profile:not([disabled])').waitFor({timeout: 60000});
  assert.equal(await page.locator('#state').textContent(), 'Учебная кукла');
  assert.equal((await page.request.post(`${base}/api/profile-settings`, {data: {id: 'unknown', settings: {}}})).status(), 400);
  assert.equal((await page.request.post(`${base}/api/profile-settings`, {data: {id: 'training', settings: {lips: {PP: {jawOpen: 7}}}}})).status(), 400);
  await page.locator('[data-viseme="PP"]').click();
  const jaw = page.locator('input[aria-label="Челюсть"]');
  await jaw.fill('23'); await jaw.dispatchEvent('input');
  await page.locator('[data-mood="happy"]').click();
  await page.locator('#save-profile').click();
  await page.getByText('Настройки профиля сохранены.', {exact: true}).waitFor();
  await page.locator('#profile').selectOption('browser-fixture');
  await page.getByText('TEST ONLY — training model fixture', {exact: true}).last().waitFor();
  await page.locator('#profile:not([disabled])').waitFor();
  assert.equal(await page.locator('#doll canvas').count(), 1);
  assert.equal(await page.locator('[data-mood="sad"]').getAttribute('aria-pressed'), 'true');
  await page.locator('[data-viseme="PP"]').click(); assert.equal(await jaw.inputValue(), '67');
  await page.locator('#profile').selectOption('training'); await page.locator('#profile:not([disabled])').waitFor();
  await page.locator('[data-viseme="PP"]').click(); assert.equal(await jaw.inputValue(), '23');
  assert.equal(await page.locator('[data-mood="happy"]').getAttribute('aria-pressed'), 'true');
  await page.route('**/profiles/browser-fixture/model.glb', route => route.fulfill({status: 404, body: 'missing'}));
  await page.locator('#profile').selectOption('browser-fixture'); await page.locator('#state.error').waitFor({timeout: 10000});
  assert.equal(await page.locator('#profile').inputValue(), 'training');
  assert.equal(await page.locator('#doll canvas').count(), 1);
  await page.unroute('**/profiles/browser-fixture/model.glb');
  await page.locator('#profile').selectOption('browser-fixture'); await page.locator('#profile:not([disabled])').waitFor();
  assert.equal(await page.locator('#profile').inputValue(), 'browser-fixture');
  await page.locator('#profile').selectOption('training'); await page.locator('#profile:not([disabled])').waitFor();
  await page.reload(); await page.locator('#profile:not([disabled])').waitFor({timeout: 60000});
  await page.locator('[data-viseme="PP"]').click(); assert.equal(await jaw.inputValue(), '23');
  // Synthetic PCM silence tests the real playback/repeat path without contacting ElevenLabs.
  const wav = Buffer.alloc(44 + 16000); wav.write('RIFF'); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(16000, 40);
  let calls = 0;
  await page.route('**/api/speak', route => { calls++; return route.fulfill({json: {audio_base64: wav.toString('base64'), alignment: {characters: ['а'], character_start_times_seconds: [0], character_end_times_seconds: [0.8]}}}); });
  await page.locator('#text').fill('а');
  await page.locator('#repeat').click(); await page.locator('#speak').click();
  await page.waitForFunction(() => document.querySelector('#state').textContent === 'Повтор');
  assert.equal(await page.locator('#profile').isDisabled(), true);
  await page.locator('#repeat').click(); await page.locator('#speak:not([disabled])').waitFor({timeout: 10000});
  await page.locator('#speak').click(); await page.locator('#speak:not([disabled])').waitFor({timeout: 10000});
  assert.equal(calls, 1);
  assert.equal(await page.locator('#profile').isDisabled(), false);
  assert.deepEqual(errors, []);
  await page.screenshot({path: new URL('../.local-preview/preview.png', import.meta.url).pathname, fullPage: true});
  console.log('PASS: login, installation/discovery, switch, per-profile settings, rollback, reload, playback/repeat/cache, one canvas, no page errors');
} finally {
  await browser.close();
  await rm(installed, {recursive: true, force: true});
  await rm(source, {recursive: true, force: true});
}
